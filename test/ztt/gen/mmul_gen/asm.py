"""Assembly and data emission primitives shared by every matrix-multiply template.

Nothing here knows about a specific instruction: these helpers turn geometry,
element widths, and expected values into GAS lines.  Instruction-specific
operand sequences live in the instruction classes and in :mod:`mmul_gen.templates`.
"""

from __future__ import annotations

from collections.abc import Sequence

from mmul_gen.machine import MachineConfig


#: Identifies a file as this generator's output, so a regeneration pass can
#: remove its own stale sources without touching a sibling generator's files in
#: a shared output directory.
GENERATOR_MARKER = "Auto-generated by test/ztt/gen/mmul_gen."

HEADER = [
    "# Copyright (c) Qualcomm Technologies, Inc. and/or its subsidiaries.",
    "# SPDX-License-Identifier: BSD-3-Clause-Clear",
    "#",
    f"# {GENERATOR_MARKER} Do not edit by hand.",
    "",
    '.include "test.inc"',
    '.include "ame_macros.inc"',
    "",
]

_DATA_DIRECTIVES = {8: ".byte", 16: ".half", 32: ".word", 64: ".dword"}


def instruction_file_name(mnemonic: str) -> str:
    """Canonical generated source name for one instruction."""

    return f"{mnemonic.replace('.', '_')}.S"


def asm_header(
    description: Sequence[str], *, acquire_backend: bool = True
) -> list[str]:
    """Prologued ``.text`` section.

    ``acquire_backend`` adds the standard ownership acquire.  The backend-state
    tests pass ``False`` because taking ownership is the thing they test.
    """

    lines = HEADER.copy()
    if description:
        lines.insert(4, "#")
        for line in reversed(description):
            lines.insert(5, f"# {line}" if line else "#")
    lines.extend([".text", ""])
    if acquire_backend:
        lines.extend(
            [
                "    li      t0, 0",
                "    ame.acquire t1, t0",
                "    EXPECT  t1, 1",
                "",
            ]
        )
    return lines


def hex_value(value: int, element_bits: int) -> str:
    return f"0x{value & ((1 << element_bits) - 1):0{element_bits // 4}x}"


def data_directive(element_bits: int) -> str:
    return _DATA_DIRECTIVES[element_bits]


def element_byte_values(value: int, element_bits: int) -> list[int]:
    masked = value & ((1 << element_bits) - 1)
    return [(masked >> (8 * offset)) & 0xFF for offset in range(element_bits // 8)]


def data_element_line(value: int, element_bits: int) -> str:
    if element_bits in _DATA_DIRECTIVES:
        return f"    {_DATA_DIRECTIVES[element_bits]} {hex_value(value, element_bits)}"
    bytes_text = ", ".join(hex_value(byte, 8) for byte in element_byte_values(value, element_bits))
    return f"    .byte {bytes_text}"


def data_element_lines(values: Sequence[int], element_bits: int) -> list[str]:
    """Emit ``values`` packed several per line to keep sources reviewable.

    Both GNU as and LLVM's integrated assembler accept comma-separated operand
    lists for the data directives, and the assembled bytes are identical to
    one-value-per-line emission.
    """

    if not values:
        return []
    if element_bits in _DATA_DIRECTIVES:
        per_line = 16 if element_bits == 8 else 8
        directive = _DATA_DIRECTIVES[element_bits]
        return [
            f"    {directive} "
            + ", ".join(hex_value(value, element_bits) for value in values[start : start + per_line])
            for start in range(0, len(values), per_line)
        ]
    per_line = 2
    return [
        "    .byte "
        + ", ".join(
            hex_value(byte, 8)
            for value in values[start : start + per_line]
            for byte in element_byte_values(value, element_bits)
        )
        for start in range(0, len(values), per_line)
    ]


def row_col_values(order: str, n: int, nelem: int) -> list[int]:
    """A 1..nelem ramp laid out row-major or column-major.

    The ramp is built here from ``n`` and ``nelem`` so the emitter depends only
    on its own arguments.
    """

    row_values = list(range(1, nelem + 1))
    if order == "rm":
        return row_values
    if order == "cm":
        return [row_values[row * n + col] for col in range(n) for row in range(n)]
    raise ValueError(f"unsupported memory order: {order}")


def pack_nibbles(values: Sequence[int]) -> list[int]:
    if len(values) % 2 != 0:
        raise ValueError("nibble list length must be even")
    return [
        (values[index] & 0xF) | ((values[index + 1] & 0xF) << 4)
        for index in range(0, len(values), 2)
    ]


def sign_extend(value: int, bits: int) -> int:
    """Interpret the low ``bits`` of ``value`` as a two's-complement integer."""

    sign_bit = 1 << (bits - 1)
    mask = (1 << bits) - 1
    value &= mask
    return value - (1 << bits) if value & sign_bit else value


def repeated_square_lines(
    label: str,
    value: int,
    element_bits: int,
    machine: MachineConfig,
) -> list[str]:
    """A formed square whose every storage slot holds ``value``."""

    square_bytes = machine.square_bytes(element_bits)
    element_count = machine.storage_elements(element_bits)
    if element_bits == 4:
        packed_byte = (value & 0xF) | ((value & 0xF) << 4)
        return [
            f".balign {square_bytes}",
            f"{label}:",
            f"    .rept {square_bytes}",
            f"    .byte {hex_value(packed_byte, 8)}",
            "    .endr",
        ]
    return [
        f".balign {square_bytes}",
        f"{label}:",
        f"    .rept {element_count}",
        data_element_line(value, element_bits),
        "    .endr",
    ]


def square_lines(
    label: str,
    values: Sequence[int],
    element_bits: int,
    machine: MachineConfig,
) -> list[str]:
    """A formed square holding one given value per storage slot.

    ``mss.rm`` stores a square as one contiguous image, so a case that checks a
    *pattern* (rather than one repeated value) needs the same byte layout here.
    """

    element_count = machine.storage_elements(element_bits)
    if len(values) != element_count:
        raise ValueError(
            f"square {label!r} needs {element_count} storage slots for "
            f"{element_bits}-bit elements, got {len(values)}"
        )
    lines = [
        f".balign {machine.square_bytes(element_bits)}",
        f"{label}:",
    ]
    if element_bits == 4:
        packed = ", ".join(hex_value(byte, 8) for byte in pack_nibbles(list(values)))
        lines.append(f"    .byte {packed}")
        return lines
    lines.extend(data_element_lines(values, element_bits))
    return lines


def dst_square_lines(machine: MachineConfig) -> list[str]:
    """Scratch square that every case stores into and verifies from."""

    square_bytes = machine.nelem * 128 // 8
    return [
        f".balign {square_bytes}",
        "dst_square:",
        f"    .rept {square_bytes}",
        "    .byte 0xa5",
        "    .endr",
        "",
    ]


