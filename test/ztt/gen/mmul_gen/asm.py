def load_byte_lines(value_reg: str, addr_reg: str, offset: int) -> list[str]:
    if -2048 <= offset <= 2047:
        return [f"    lbu     {value_reg}, {offset}({addr_reg})"]
    return [
        f"    li      {value_reg}, {offset}",
        f"    add     {value_reg}, {addr_reg}, {value_reg}",
        f"    lbu     {value_reg}, 0({value_reg})",
    ]


def check_dst_lines(
    expected: int,
    element_bits: int,
    *,
    machine: MachineConfig,
    label: str = "dst_square",
    element_count: int | None = None,
) -> list[str]:
    """Verify the first and last stored element of a uniform expected square."""

    checked_elements = (
        machine.storage_elements(element_bits) if element_count is None else element_count
    )
    if checked_elements <= 0:
        raise ValueError("element_count must be positive")

    if element_bits == 4:
        packed_byte = (expected & 0xF) | ((expected & 0xF) << 4)
        packed_bytes = (checked_elements * element_bits + 7) // 8
        return [
            f"    la      t3, {label}",
            "    lbu     t4, 0(t3)",
            f"    EXPECT  t4, {packed_byte}",
            *load_byte_lines("t4", "t3", packed_bytes - 1),
            f"    EXPECT  t4, {packed_byte}",
            "",
        ]

    elem_bytes = max(1, element_bits // 8)
    masked = expected & ((1 << element_bits) - 1)
    lines = [f"    la      t3, {label}"]
    for byte_offset in range(elem_bytes):
        lines.extend(
            [
                f"    lbu     t4, {byte_offset}(t3)",
                f"    EXPECT  t4, {(masked >> (8 * byte_offset)) & 0xFF}",
            ]
        )

    last_elem_offset = (checked_elements - 1) * elem_bytes
    for byte_offset in range(elem_bytes):
        lines.extend(
            [
                *load_byte_lines("t4", "t3", last_elem_offset + byte_offset),
                f"    EXPECT  t4, {(masked >> (8 * byte_offset)) & 0xFF}",
            ]
        )

    lines.append("")
    return lines


def check_dst_element_lines(
    expected: int,
    element_bits: int,
    elem_index: int,
    label: str = "dst_square",
) -> list[str]:
    """Verify exactly one element of a stored square."""

    if element_bits == 4:
        shift = 4 if elem_index % 2 else 0
        lines = [
            f"    la      t3, {label}",
            *load_byte_lines("t4", "t3", elem_index // 2),
        ]
        if shift:
            lines.append("    srli    t4, t4, 4")
        lines.extend(
            [
                "    andi    t4, t4, 0xf",
                f"    EXPECT  t4, {expected & 0xF}",
            ]
        )
        return lines

    elem_bytes = element_bits // 8
    masked = expected & ((1 << element_bits) - 1)
    elem_offset = elem_index * elem_bytes
    lines = [f"    la      t3, {label}"]
    for byte_offset in range(elem_bytes):
        lines.extend(
            [
                *load_byte_lines("t4", "t3", elem_offset + byte_offset),
                f"    EXPECT  t4, {(masked >> (8 * byte_offset)) & 0xFF}",
            ]
        )
    lines.append("")
    return lines


def check_bytes_lines(
    label: str, expected_bytes: Sequence[int], offsets: Sequence[int]
) -> list[str]:
    """Verify selected byte offsets of a labelled byte image."""

    lines = [f"    la      t3, {label}"]
    for offset in offsets:
        lines.extend(
            [
                *load_byte_lines("t4", "t3", offset),
                f"    EXPECT  t4, {expected_bytes[offset] & 0xFF}",
            ]
        )
    lines.append("")
    return lines


