"""The command-line entry point writes only this generator's own output."""

from __future__ import annotations

import contextlib
import io
import json
import tempfile
import unittest
from pathlib import Path

from mmul_gen.__main__ import main, parse_args
from mmul_gen.catalog import ALL_INSTRUCTIONS, TYPE_REGISTER_INSTRUCTIONS
from mmul_gen.tests.helpers import MACRO_FILE


GENERATED_NAMES = tuple(
    instruction.file_name for instruction in ALL_INSTRUCTIONS
)


@contextlib.contextmanager
def out_dir():
    with tempfile.TemporaryDirectory() as directory:
        yield Path(directory)


class CliTests(unittest.TestCase):
    def run_cli(self, arguments: list[str]) -> str:
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            main(arguments)
        return output.getvalue()

    def test_defaults_generate_the_static_uint8_configuration(self) -> None:
        args = parse_args([])
        self.assertEqual(args.n, 8)
        self.assertEqual(args.uds, 8)
        self.assertEqual(args.m, 32)
        self.assertEqual(args.acc, 4)
        self.assertEqual(args.macro_file, MACRO_FILE)

    def test_n_and_uds_are_accepted_explicitly(self) -> None:
        args = parse_args(["--n", "16", "--uds", "16"])
        self.assertEqual(args.n, 16)
        self.assertEqual(args.uds, 16)

    def test_list_prints_the_inventory_for_the_configuration(self) -> None:
        described = json.loads(self.run_cli(["--list", "--uds", "16"]))
        self.assertEqual(
            [entry["name"] for entry in described],
            [instruction.name for instruction in ALL_INSTRUCTIONS],
        )
        by_name = {entry["name"]: entry for entry in described}
        self.assertIn("AME_UINT16_DTYPE", by_name["mmulacc.2d"]["dtypes"])
        # A dtype-free instruction reports no datatype coverage at all.
        self.assertEqual(by_name["ame.acquire"]["datatype_domains"], [])
        self.assertEqual(by_name["ame.acquire"]["dtypes"], [])

    def test_out_dir_is_required_unless_listing(self) -> None:
        with self.assertRaisesRegex(SystemExit, "out-dir is required"):
            main([])

    def test_generation_is_idempotent_and_leaves_no_temporary_files(self) -> None:
        with out_dir() as directory:
            self.run_cli(["--out-dir", str(directory)])
            first = {path.name: path.read_text() for path in directory.iterdir()}
            self.assertEqual(sorted(first), sorted(GENERATED_NAMES))
            self.run_cli(["--out-dir", str(directory)])
            second = {path.name: path.read_text() for path in directory.iterdir()}
            self.assertEqual(first, second)
            self.assertEqual([path for path in directory.iterdir() if path.suffix == ".tmp"], [])

    def test_stale_output_is_removed_only_when_this_generator_wrote_it(self) -> None:
        with out_dir() as directory:
            self.run_cli(["--out-dir", str(directory)])
            stale = directory / "mmulold_2d.S"
            stale.write_text("# Auto-generated by test/ztt/gen/mmul_gen.\nstale\n")
            foreign = directory / "other_family.S"
            foreign.write_text("# Auto-generated by test/ztt/gen/mmul_gen/__main__.py\nkeep\n")
            self.run_cli(["--out-dir", str(directory)])
            self.assertFalse(stale.exists())
            self.assertTrue(foreign.exists())
            self.assertEqual(
                sorted(path.name for path in directory.iterdir()),
                sorted((*GENERATED_NAMES, "other_family.S")),
            )

    def test_a_partial_family_pass_keeps_the_other_families_output(self) -> None:
        with out_dir() as directory:
            self.run_cli(["--out-dir", str(directory)])
            before = {path.name: path.read_text() for path in directory.iterdir()}
            self.run_cli(["--family", "type_register", "--out-dir", str(directory)])
            after = {path.name: path.read_text() for path in directory.iterdir()}
            self.assertEqual(before, after)

    def test_a_partial_family_pass_writes_only_that_family(self) -> None:
        with out_dir() as directory:
            self.run_cli(["--family", "type_register", "--out-dir", str(directory)])
            self.assertEqual(
                sorted(path.name for path in directory.iterdir()),
                sorted(
                    instruction.file_name
                    for instruction in TYPE_REGISTER_INSTRUCTIONS
                ),
            )

    def test_every_generated_file_ends_with_exactly_one_newline(self) -> None:
        with out_dir() as directory:
            self.run_cli(["--out-dir", str(directory)])
            for name in GENERATED_NAMES:
                text = (directory / name).read_text()
                with self.subTest(source=name):
                    self.assertTrue(text.endswith("\n"))
                    self.assertFalse(text.endswith("\n\n"))


if __name__ == "__main__":
    unittest.main()
