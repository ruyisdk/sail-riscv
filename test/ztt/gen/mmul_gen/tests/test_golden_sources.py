"""The generator's emitted assembly, frozen.

These hashes pin the emitted assembly of five configurations, so a template
change that alters emitted assembly fails here.

The hashes are of the attribution-normalised text: the comment names the
generator that wrote the file, which is the one intended difference.
"""

from __future__ import annotations

import hashlib
import json
import unittest
from pathlib import Path

from mmul_gen.catalog import generate_all
from mmul_gen.tests.helpers import machine

GOLDEN = Path(__file__).with_name("golden_sources.json")


def normalize(text: str) -> str:
    """Drop the generator-attribution comment."""

    return "\n".join(
        "Auto-generated" if "Auto-generated by" in line else line
        for line in text.splitlines()
    )


def digest(text: str) -> str:
    return hashlib.sha256(normalize(text).encode()).hexdigest()


class GoldenSourceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.golden: dict[str, dict[str, str]] = json.loads(GOLDEN.read_text())

    def test_every_configuration_matches_the_frozen_output(self) -> None:
        for label, expected in sorted(self.golden.items()):
            n, uds, m_regs, acc_regs = (int(part[1:]) for part in label.split("_"))
            config = machine(n=n, uds=uds, num_m_regs=m_regs, num_acc_regs=acc_regs)
            actual = {source.name: digest(source.text) for source in generate_all(config)}
            with self.subTest(config=label):
                self.assertEqual(sorted(actual), sorted(expected))
                for name, expected_digest in expected.items():
                    self.assertEqual(actual[name], expected_digest, name)


if __name__ == "__main__":
    unittest.main()
